async function preflight() {
  const { error } = await supabase.from('meals').select('id, ustensiles').limit(1);
  if (error && /ustensiles|schema cache/i.test(error.message)) {
    console.error('❌ La colonne "ustensiles" n\'existe pas encore dans la table "meals".');
    console.error('');
    console.error('👉 Applique d\'abord la migration 00004 :');
    console.error('   1. npm run db:migrate  (affiche le SQL)');
    console.error('   2. Colle supabase/migrations/00004_budget_prix_ustensiles.sql dans le SQL Editor Supabase');
    console.error('   3. Relance : npm run seed:recettes');
    process.exit(1);
  }
  if (error) throw error;
}

// Normalise les apostrophes (droite ' vs typographique ’) pour le matching
function normalizeTitre(t: string): string {
  return t.replace(/[’‘`]/g, "'");
}

async function main() {
  console.log('📖 Mise à jour des recettes détaillées...\n');
  await preflight();

  let updated = 0;
  let missing: string[] = [];

  const { data: meals, error } = await supabase.from('meals').select('id, titre');
  if (error) throw error;

  const titres = new Map<string, string>();
  for (const r of RECETTES) titres.set(normalizeTitre(r.titre), r.titre);

  for (const meal of meals || []) {
    const recette = RECETTES.find(r => r.titre === meal.titre)
      || RECETTES.find(r => normalizeTitre(r.titre) === normalizeTitre(meal.titre));
    if (!recette) {
      missing.push(meal.titre);
      continue;
    }
    const update: any = { instructions: recette.r };
    if (recette.u && recette.u.length > 0) update.ustensiles = recette.u;

    const { error: upErr } = await supabase.from('meals').update(update).eq('id', meal.id);
    if (upErr) {
      console.log(`❌ ${meal.titre}: ${upErr.message}`);
    } else {
      updated++;
    }
  }

  console.log(`✅ ${updated} recettes mises à jour avec un pas-à-pas détaillé.`);
  if (missing.length > 0) {
    console.log(`⚠️  ${missing.length} recettes sans correspondance (titres différents) :`);
    console.log('   ' + missing.join(' · '));
  }
}

main().catch(console.error);
